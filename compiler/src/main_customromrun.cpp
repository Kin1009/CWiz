// main_customromrun.cpp - run a custom ROM image on top of an existing
// CasioEmuMsvc model.
//
// What it does:
//     1. copies the matching model folder  (models/fx-580VN X  or  models/fx-880BTG)
//     2. renames the duplicate to the custom ROM's name  (models/<rom-name>)
//     3. keeps the model's original ROM as a backup (<rom>.orig) and copies the
//        custom ROM over it, replacing it
//     4. launches CasioEmuMsvc with that (custom) model
#include <sys/types.h>
#include <unistd.h>

#include <algorithm>
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <string>
#include <vector>

#include "cli.hpp"
#include "diag.hpp"
#include "modelinfo.hpp"

using namespace wiz;
namespace fs = std::filesystem;

static const char* MARKER = ".customrom";  // marks a folder created by this tool
static const char* TOOL = "customromrun";

static std::string g_repo_root;
static std::string g_emu_root;
static Diag g_d(TOOL);

[[noreturn]] static void die(const std::string& msg) {
    g_d.error(msg);
    std::exit(1);
}

static std::string find_repo_root(const char* argv0) {
    if (const char* r = std::getenv("WIZ_ROOT")) return r;
    std::error_code ec;
    fs::path exe = fs::weakly_canonical(fs::path(argv0 ? argv0 : ""), ec);
    if (!ec) exe = exe.parent_path();
    std::vector<fs::path> cands = {exe, exe / "..", fs::current_path(ec)};
    for (const auto& c : cands) {
        std::error_code e2;
        if (fs::exists(c / "compiler", e2) || fs::exists(c / "emulator", e2)) return c.string();
    }
    return exe.string();
}

static std::string find_emu_root() {
    std::vector<std::string> cands;
    if (const char* r = std::getenv("CASIOEMU_ROOT")) cands.push_back(r);
    cands.push_back(g_repo_root + "/emulator");
    cands.push_back(g_repo_root + "/CasioEmuMsvc-Mac-stable");
    cands.push_back(g_repo_root);
    for (const auto& cand : cands) {
        std::error_code ec;
        if (!cand.empty() && fs::is_directory(fs::path(cand) / "models", ec)) {
            std::error_code e2;
            return fs::weakly_canonical(cand, e2).string();
        }
    }
    return g_repo_root + "/emulator";
}

static std::string abspath(const std::string& p) {
    std::error_code ec;
    fs::path a = fs::absolute(p, ec);
    if (ec) return p;
    return a.lexically_normal().string();
}

// Return the ROM filename declared in the model's config.bin (default: rom.bin).
static std::string read_rom_path(const std::string& model_dir) {
    std::string config = model_dir + "/config.bin";
    std::error_code ec;
    if (fs::exists(config, ec)) {
        bool ok = false;
        std::vector<uint8_t> buf = read_binary_file(config, &ok);
        if (ok) {
            std::string rom = model_rom_path(buf);
            if (!rom.empty()) return rom;
        }
    }
    return "rom.bin";
}

static std::string find_base_model(const std::string& models_dir, const std::string& selector) {
    std::error_code ec;
    if (!fs::is_directory(models_dir, ec)) die("models directory not found: " + models_dir);
    std::vector<std::string> names;
    for (const auto& e : fs::directory_iterator(models_dir, ec)) {
        if (!e.is_directory()) continue;
        std::string name = e.path().filename().string();
        if (fs::exists(e.path() / MARKER, ec)) continue;  // generated by this tool
        if (name.find(selector) != std::string::npos) names.push_back(name);
    }
    if (names.empty()) {
        std::vector<std::string> avail;
        for (const auto& e : fs::directory_iterator(models_dir, ec))
            if (e.is_directory()) avail.push_back(e.path().filename().string());
        std::sort(avail.begin(), avail.end());
        die(fmt("no model matching '%s' in %s (available: %s)", selector.c_str(),
                models_dir.c_str(), avail.empty() ? "(none)" : join(avail, ", ").c_str()));
    }
    std::sort(names.begin(), names.end(), [](const std::string& a, const std::string& b) {
        if (a.size() != b.size()) return a.size() < b.size();
        return a < b;
    });
    return names[0];
}

// Return ("open", app_bundle) or ("exec", binary).
static std::pair<std::string, std::string> resolve_launch(const std::string& explicit_bin) {
    std::string binary;
    std::error_code ec;
    if (!explicit_bin.empty()) {
        if (!fs::exists(explicit_bin, ec)) die("emulator binary not found: " + explicit_bin);
        binary = explicit_bin;
    } else {
        std::string app = g_emu_root + "/CasioEmuMsvc.app/Contents/MacOS/CasioEmuMsvc";
        if (fs::exists(app, ec)) {
            binary = app;
        } else {
            for (auto it = fs::recursive_directory_iterator(g_emu_root, ec);
                 it != fs::recursive_directory_iterator(); ++it) {
                if (it->path().filename() == "CasioEmuMsvc" &&
                    ::access(it->path().c_str(), X_OK) == 0) {
                    binary = it->path().string();
                    break;
                }
            }
            if (binary.empty()) die("could not find the CasioEmuMsvc binary; pass --emu PATH");
        }
    }
    std::error_code e2;
    fs::path real = fs::weakly_canonical(binary, e2);
    std::string s = real.string();
    std::vector<std::string> parts;
    {
        std::string cur;
        for (char c : s) {
            if (c == '/') {
                if (!cur.empty()) parts.push_back(cur);
                cur.clear();
            } else {
                cur += c;
            }
        }
        if (!cur.empty()) parts.push_back(cur);
    }
    for (int i = (int)parts.size() - 1; i >= 0; i--) {
        if (ends_with(parts[(size_t)i], ".app")) {
            std::string bundle;
            for (int k = 0; k <= i; k++) bundle += "/" + parts[(size_t)k];
            std::error_code e3;
            if (fs::is_directory(bundle, e3)) return {"open", bundle};
        }
    }
    return {"exec", binary};
}

static void launch(const std::vector<std::string>& cmd, const std::string& cwd) {
    std::vector<char*> argv;
    for (const auto& s : cmd) argv.push_back(const_cast<char*>(s.c_str()));
    argv.push_back(nullptr);
    pid_t pid = fork();
    if (pid < 0) die("failed to launch emulator: fork failed");
    if (pid == 0) {
        setsid();
        if (chdir(cwd.c_str()) != 0) _exit(127);
        execvp(argv[0], argv.data());
        _exit(127);
    }
}

int main(int argc, char** argv) {
    g_argv0 = argv[0];
    g_repo_root = find_repo_root(argv[0]);
    g_emu_root = find_emu_root();
    std::string default_models = g_emu_root + "/models";

    std::vector<CliOption> opts = {
        {"--model", "model", true},
        {"--models", "models", true},
        {"--emu", "emu", true},
        {"--no-launch", "no-launch"},
        {"--dry-run", "dry-run"},
        {"--color", "color", true, true, "always", {"auto", "always", "never"}},
        {"-h", "help"},
        {"--help", "help"},
    };
    Cli args;
    std::string err;
    if (!parse_cli(argc, argv, opts, args, err)) {
        std::fprintf(stderr, "%s: error: %s\n", TOOL, err.c_str());
        return 2;
    }
    if (args.has("help")) {
        std::fputs(
            "customromrun - run a custom ROM image on top of an existing CasioEmuMsvc model.\n"
            "\n"
            "Usage:\n"
            "    customromrun --model 580|880 rom.bin [options]\n"
            "\n"
            "Options:\n"
            "    --model 580|880     which base model to use (required)\n"
            "    --models DIR        models directory  (default: <emulator-tree>/models)\n"
            "    --emu PATH          path to the CasioEmuMsvc binary\n"
            "    --no-launch         do everything except launching the emulator\n"
            "    --dry-run           print the plan without changing anything\n"
            "    --color[=WHEN]      colour output: auto | always | never\n"
            "    -h, --help          show this help\n",
            stdout);
        return 0;
    }

    try {
        set_color_mode_from_arg(args.value("color", "auto"));
    } catch (const std::exception& e) {
        std::fprintf(stderr, "%s: error: %s\n", TOOL, e.what());
        return 2;
    }

    if (!args.has("model")) die("--model is required (580 or 880)");
    if (args.positional.empty()) die("no custom ROM given");

    std::error_code ec;
    std::string rom = abspath(args.positional[0]);
    if (!fs::is_regular_file(rom, ec)) die("custom ROM not found: " + rom);

    std::string models_dir = abspath(args.value("models", default_models));
    std::string base_name = find_base_model(models_dir, args.value("model"));
    std::string base_dir = models_dir + "/" + base_name;

    std::string rom_name = path_basename(splitext_root(rom));
    if (rom_name.empty()) rom_name = "customrom";
    std::string dst_dir = models_dir + "/" + rom_name;

    if (abspath(dst_dir) == abspath(base_dir))
        die(fmt("custom ROM name '%s' collides with the base model folder", rom_name.c_str()));

    std::string rom_file = read_rom_path(base_dir);
    std::string dst_rom = dst_dir + "/" + rom_file;
    std::string backup_rom = dst_rom + ".orig";

    const bool tty = stdout_is_tty();
    std::fputs(fmt("%s %s -> %s\n", bold(TOOL, tty).c_str(), base_dir.c_str(), dst_dir.c_str())
                   .c_str(),
               stdout);
    std::fputs(fmt("    %s\n",
                   dim(fmt("base model %s | custom rom %s | replaces %s", base_name.c_str(),
                           rom.c_str(), path_basename(dst_rom).c_str()),
                       tty)
                       .c_str())
                   .c_str(),
               stdout);

    if (args.has("dry-run")) {
        std::fputs(fmt("    %s\n", yellow("dry run - nothing changed", tty).c_str()).c_str(),
                   stdout);
        return 0;
    }

    // 1) copy the model folder, 2) under the custom ROM's name
    if (fs::exists(dst_dir, ec)) {
        if (!fs::exists(fs::path(dst_dir) / MARKER, ec))
            die(fmt("destination exists and was not created by customromrun: %s\n"
                    "       remove it manually or choose a different ROM filename",
                    dst_dir.c_str()));
        fs::remove_all(dst_dir, ec);
    }
    fs::copy(base_dir, dst_dir,
             fs::copy_options::recursive | fs::copy_options::copy_symlinks, ec);
    if (ec) die(fmt("could not copy model folder: %s", ec.message().c_str()));

    // 3) preserve the original ROM, then copy the custom ROM over it (replace)
    if (fs::exists(dst_rom, ec) && !fs::exists(backup_rom, ec)) fs::copy_file(dst_rom, backup_rom, ec);
    fs::copy_file(rom, dst_rom, fs::copy_options::overwrite_existing, ec);
    if (ec) die(fmt("could not write the custom ROM: %s", ec.message().c_str()));
    write_text_file(dst_dir + "/" + MARKER,
                    fmt("generated by customromrun\nbase model: %s\ncustom rom: %s\n",
                        base_name.c_str(), rom.c_str()));

    std::fputs(fmt("    %s model prepared at %s\n", green("OK", tty).c_str(), dst_dir.c_str())
                   .c_str(),
               stdout);

    // 4) launch CasioEmuMsvc with that model
    if (args.has("no-launch")) return 0;
    auto launch_spec = resolve_launch(args.value("emu"));
    std::vector<std::string> cmd;
    if (launch_spec.first == "open")
        cmd = {"open", "-n", launch_spec.second, "--args", dst_dir};
    else
        cmd = {launch_spec.second, dst_dir};
    std::fputs(fmt("    launching: %s\n", join(cmd, " ").c_str()).c_str(), stdout);
    launch(cmd, g_emu_root);
    return 0;
}
