#!/usr/bin/env python3
"""Generate a CWiz chooser menu from a list of items.

Usage:
  python3 tools/gen_chooser.py --name demo \
      --items "Calculate,Complex,Base-N,..." --out ui/menus/demo.cwiz

The generated module includes the shared chooser, defines a rom8 blob, and
exposes <name>_chooser(variant): 0 = big (4/page), 1 = small (6x2).
"""

import argparse
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--items", required=True)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    items = [x.strip() for x in args.items.split(",") if x.strip()]
    if not items:
        raise SystemExit("no items")
    blob = bytearray()
    for text in items:
        blob.extend(text.encode("ascii", "replace"))
        blob.append(0)
    if len(blob) > 500:
        raise SystemExit("menu exceeds the 500-byte chooser blob")

    lines = [
        f"// Generated by tools/gen_chooser.py: {len(items)} items.",
        '#include "../chooser.cwiz"',
        "",
        f"rom8 {args.name}_blob[{len(blob)}] = {{",
    ]
    for i in range(0, len(blob), 16):
        lines.append("    " + ", ".join(str(b) for b in blob[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append(f"int {args.name}_chooser(int variant) {{")
    lines.append(f"    int i = 0;")
    lines.append(f"    while (i < {len(blob)}) {{ chooser_blob[i] = {args.name}_blob[i]; i = i + 1; }}")
    lines.append(f"    chooser_count = {len(items)};")
    lines.append(f"    chooser_variant = variant;")
    lines.append(f"    return chooser_run();")
    lines.append("}")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out} ({len(items)} items, {len(blob)} bytes)")


if __name__ == "__main__":
    main()
