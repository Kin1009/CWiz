#!/usr/bin/env python3
"""Generate build/version.cwiz: model/version/serial constants for diagnostics.

Serial layout (12 chars, no hyphens): MMM + BBBBB + NNNN
  MMM   model identifier (580 -> "058", 880 -> "088", 880 PLUS -> "188")
  BBBBB build number in hex (5 digits, non-zero)
  NNNN  random hex
"""

import subprocess
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
OUT = PROJECT / "build" / "version.cwiz"

# Predefined major/minor for this project.
MAJ = 0
MIN = 1


def build_number() -> int:
    """Build number since the last minor: git commit count, at least 1."""
    try:
        out = subprocess.run(
            ["git", "-C", str(PROJECT), "rev-list", "--count", "HEAD"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
        value = int(out)
    except Exception:
        value = 1
    return max(1, value) & 0xFFFFF


def model_code() -> str:
    # fx-580VN X is the only packaged model in this project.
    return "058"


def main() -> None:
    bld = build_number()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Auto-generated by tools/gen_version.py. Do not edit.\n"
        f"#define CWIZ_VERSION_MAJ {MAJ}\n"
        f"#define CWIZ_VERSION_MIN {MIN}\n"
        f"#define CWIZ_VERSION_BUILD {bld}\n"
        f'#define CWIZ_VERSION_TEXT "{MAJ}.{MIN}.{bld}"\n',
        encoding="utf-8",
    )
    print(f"Wrote {OUT} (version {MAJ}.{MIN}.{bld})")


if __name__ == "__main__":
    main()
